async function kie(path, apiKey, body) {
  let response;
  try {
    response = await fetch(`https://api.kie.ai/api/v1/${path}`, {
      method: body ? "POST" : "GET",
      headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
      body: body ? JSON.stringify(body) : undefined,
      signal: AbortSignal.timeout(30000)
    });
  } catch {
    throw new ORPCError("BAD_GATEWAY", { message: "Kie.ai is unavailable. Please try again." });
  }
  const data = await response.json();
  if (!response.ok || data.code !== 200) {
    const message = data.code === 401 ? "Your Kie.ai API key is invalid. Update it in API settings." : data.code === 402 ? "Not enough Kie.ai credits." : String(data.msg || "Kie.ai could not process this request.");
    throw new ORPCError("BAD_REQUEST", { message });
  }
  return data.data;
}
